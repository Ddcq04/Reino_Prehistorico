    <main class="contenido">
        <section class="vidrio">
            <h2>Duración</h2>
            <p>
                El período Cretácico abarcó desde hace <strong>145 hasta 66 millones de años</strong>,
                siendo el tercer y último período de la Era Mesozoica. Marcó tanto el apogeo como la 
                súbita extinción de los dinosaurios.
            </p>
        </section>

        <section class="vidrio">
            <h2>Geografía y continentes</h2>
            <p>
                Los continentes continuaron separándose hasta adquirir formas reconocibles:
                <strong>América del Norte</strong> se separó de <strong>Europa</strong>,
                <strong>América del Sur</strong> de <strong>África</strong>,
                y la <strong>India</strong> comenzó su viaje hacia el norte.
            </p>
        </section>

        <section class="vidrio">
            <h2>Clima</h2>
            <p>
                El clima fue generalmente <strong>cálido y tropical</strong>, con temperaturas más altas
                que en la actualidad. Sin embargo, hacia el final del período comenzó un 
                <strong>enfriamiento gradual</strong>.
            </p>
        </section>

        <section class="vidrio">
            <h2>Flora - La Revolución de las Flores</h2>
            <p>La gran innovación del Cretácico fue la aparición y expansión de:</p>
            <ul>
                <li><strong>Angiospermas</strong> (plantas con flores)</li>
                <li>Primeras hierbas y pastos</li>
                <li>Árboles como magnolias y laureles</li>
                <li>Coníferas que seguían siendo dominantes</li>
            </ul>
        </section>

        <section class="vidrio">
            <h2>Fauna Terrestre</h2>
            <p>Los dinosaurios alcanzaron su máxima diversidad:</p>
            <ul>
                <li><strong>Tyrannosaurus rex</strong> - El rey depredador</li>
                <li><strong>Triceratops</strong> - Dinosaurio con cuernos</li>
                <li><strong>Velociraptor</strong> - Cazador ágil e inteligente</li>
                <li><strong>Ankylosaurus</strong> - Tanque viviente acorazado</li>
                <li><strong>Parasaurolophus</strong> - Dinosaurio con cresta</li>
            </ul>
        </section>

        <section class="vidrio">
            <h2>Vida Marina</h2>
            <p>Los océanos estaban dominados por reptiles marinos gigantes:</p>
            <ul>
                <li><strong>Mosasaurios</strong> - Superdepredadores marinos</li>
                <li><strong>Plesiosaurios</strong> (como Elasmosaurus)</li>
                <li><strong>Ammonites</strong> - Moluscos con conchas espirales</li>
                <li>Primeros tiburones modernos</li>
            </ul>
        </section>

        <section class="vidrio">
            <h2>Evolución de las Aves</h2>
            <p>
                Las aves continuaron diversificándose, algunas alcanzando tamaños gigantescos
                como el <strong>Argentavis</strong>, aunque este apareció después del Cretácico.
                Muchas aves aún conservaban dientes.
            </p>
        </section>

        <section class="vidrio">
            <h2>La Extinción Masiva del Cretácico-Paleógeno</h2>
            <p>
                Hace <strong>66 millones de años</strong>, un asteroide de aproximadamente 10 km
                de diámetro impactó en lo que hoy es la Península de Yucatán (México),
                creando el cráter de Chicxulub.
            </p>
            <p><strong>Consecuencias:</strong></p>
            <ul>
                <li>Oscurecimiento global por polvo y cenizas</li>
                <li>Tsunamis gigantescos</li>
                <li>Incendios forestales a escala global</li>
                <li>Lluvia ácida y cambios climáticos drásticos</li>
                <li>Extinción del <strong>75% de todas las especies</strong></li>
            </ul>
            <p>
                Este evento marcó el <strong>fin de los dinosaurios no avianos</strong> y
                permitió la ascensión de los mamíferos.
            </p>
        </section>

        <section class="vidrio">
            <h2>Legado del Cretácico</h2>
            <p>
                Aunque terminó en catástrofe, el Cretácico dejó un mundo transformado:
                las plantas con flores dominaron los paisajes, los mamíferos sobrevivieron
                para diversificarse, y las aves (únicos dinosaurios sobrevivientes)
                heredaron los cielos.
            </p>
        </section>

