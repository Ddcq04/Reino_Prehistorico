    <p class="subtitu">La Era del Hielo y el Surgimiento de la Humanidad</p>


<main class="contenido">

    <section class="vidrio">
        <h2>Duración</h2>
        <p>
            El Cuaternario abarca desde hace <strong class="texto-cuaternario">2.6 millones de años hasta la actualidad</strong>,
            siendo el tercer y último periodo de la Era Cenozoica. Es conocido como la "Era del Hielo" debido a
            las glaciaciones periódicas que han marcado este periodo.
        </p>
    </section>

    <section class="vidrio">
        <h2>Divisiones del Cuaternario</h2>
        <p>El Cuaternario se divide en dos épocas principales:</p>
    
        <ul>
            <li>Pleistoceno (2.6 Ma - 11,700 años)</li>
            <li>Holoceno (11,700 años - Actualidad)</li>
        </ul>
        <p >
            Algunos científicos proponen una nueva época: el <strong>Antropoceno</strong>, marcado por el impacto humano significativo en la Tierra.
        </p>
    </section>

    <section class="vidrio">
        <h2>Las Glaciaciones Cuaternarias</h2>
        <p>
            El Cuaternario se caracteriza por <strong>ciclos glaciares e interglaciares</strong>.
            Durante los períodos glaciares, enormes capas de hielo cubrieron gran parte de
            América del Norte, Europa y Asia.
        </p>
        <ul>
            <li><strong>Glaciación de Würm/Wisconsin</strong> (la última gran glaciación)</li>
            <li><strong>Glaciación de Riss/Illinois</strong></li>
            <li><strong>Glaciación de Mindel/Kansan</strong></li>
            <li><strong>Glaciación de Günz/Nebraska</strong> (la más antigua del Cuaternario)</li>
        </ul>
    </section>

    <section class="vidrio">
        <h2>Clima</h2>
        <p>
            El clima del Cuaternario ha estado dominado por <strong>oscilaciones extremas</strong>
            entre períodos glaciares (fríos) e interglaciares (templados). Estos ciclos están
            relacionados con variaciones en la órbita terrestre (Ciclos de Milankovitch).
        </p>
    </section>

    <section class="vidrio">
        <h2>Megafauna del Cuaternario</h2>
        <p>
            Durante el Pleistoceno, el planeta estuvo poblado por una impresionante megafauna:
        </p>
        <ul>
            <li><strong>Mamut lanudo</strong> (Mammuthus primigenius)</li>
            <li><strong>Rinoceronte lanudo</strong> (Coelodonta antiquitatis)</li>
            <li><strong>Megaterio</strong> (perezoso gigante)</li>
            <li><strong>Smilodon</strong> (tigre dientes de sable)</li>
            <li><strong>Gliptodonte</strong> (armadillo gigante)</li>
            <li><strong>Moa</strong> (ave gigante no voladora de Nueva Zelanda)</li>
            <li><strong>Dodo</strong> (extinto en el Holoceno, 1662)</li>
        </ul>
    </section>

    <section class="vidrio">
        <h2>Evolución Humana</h2>
        <p>
            El Cuaternario es testigo de la evolución y dispersión del género Homo:
        </p>
        <ul>
            <li><strong>Homo habilis</strong> (primer fabricante de herramientas, ~2.4 Ma)</li>
            <li><strong>Homo erectus</strong> (primer homínido en salir de África, ~1.9 Ma)</li>
            <li><strong>Homo neanderthalensis</strong> (Europa y Asia, ~400,000-40,000 años)</li>
            <li><strong>Homo sapiens</strong> (nuestra especie, aparecida ~300,000 años atrás)</li>
            <li><strong>Homo floresiensis</strong> ("hobbit" de Indonesia)</li>
            <li><strong>Denisovanos</strong> (descubiertos recientemente en Siberia)</li>
        </ul>
    </section>

    <section class="vidrio">
        <h2>Migraciones Humanas</h2>
        <p>
            Los humanos modernos se dispersaron por todo el planeta:
        </p>
        <ul>
            <li><strong>Salida de África</strong> (~70,000-50,000 años atrás)</li>
            <li><strong>Poblamiento de Eurasia</strong></li>
            <li><strong>Cruce del estrecho de Bering</strong> hacia América (~15,000 años)</li>
            <li><strong>Poblamiento de Oceanía</strong> (~40,000 años)</li>
        </ul>
    </section>

    <section class="vidrio">
        <h2>Extinción de la Megafauna</h2>
        <p>
            A finales del Pleistoceno y durante el Holoceno, se produjo una
            <strong>extinción masiva de grandes mamíferos</strong>:
        </p>
        <ul>
            <li>Desaparición de la mayoría de la megafauna americana (~10,000 años)</li>
            <li>Extinción de mamuts lanudos (~4,000 años, isla de Wrangel)</li>
            <li>Desaparición de la megafauna australiana (~40,000 años)</li>
            <li>Extinción de la megafauna de Madagascar (~1,000 años)</li>
            <li>Extinción de las moas de Nueva Zelanda (~1400 d.C.)</li>
        </ul>
        <p>
            Las causas incluyen <strong>cambio climático</strong> y posiblemente
            <strong>la caza humana</strong> (hipótesis de la "sobrematanza").
        </p>
    </section>

    <section  class="vidrio">
        <h2>El Holoceno y la Revolución Neolítica</h2>
        <p>
            Con el final de la última glaciación (~11,700 años), comenzó el Holoceno,
            caracterizado por un clima más estable que permitió:
        </p>
        <ul>
            <li><strong>Desarrollo de la agricultura</strong> (~10,000 años)</li>
            <li><strong>Domesticación de animales</strong></li>
            <li><strong>Formación de las primeras ciudades</strong></li>
            <li><strong>Invención de la escritura</strong> (~5,500 años)</li>
            <li><strong>Revoluciones industriales y tecnológicas</strong></li>
        </ul>
    </section>

    <section class="vidrio">
        <h2>Importancia del Cuaternario</h2>
        <p>
            El Cuaternario es el periodo en el que <strong>nuestra especie evolucionó y dominó el planeta</strong>.
            Los cambios climáticos cíclicos moldearon la evolución humana y la distribución de la vida.
            La última gran extinción (megafauna) y el impacto humano creciente marcan la transición
            hacia lo que algunos llaman el <strong>Antropoceno</strong>, donde la actividad humana
            es la principal fuerza geológica.
        </p>
        <p>
            Comprender el Cuaternario es esencial para entender <strong>nuestro lugar en la historia de la Tierra</strong>
            y los desafíos ambientales que enfrentamos hoy.
        </p>
    </section>

